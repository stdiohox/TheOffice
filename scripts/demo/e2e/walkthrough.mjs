await step('rules: staff cannot change settings, see insights, or read others leave', page, async () => {
  const r = await db(page, async () => {
    const supabase = window.__supabase
    const settings = await supabase.from('office_settings').update({ enforce_activity: true }).eq('id', 1).select()
    const insights = await supabase.rpc('office_insights', { p_days: 5 })
    const me = (await supabase.auth.getUser()).data.user.id
    const leave = await supabase.from('office_leave_requests').select('user_id, note')
    const again = await supabase.rpc('submit_report', { p_kind: 'signin', p_body: 'x', p_link: null, p_files: [] })
    return { changed: settings.data?.length ?? 0, insights: insights.error?.code, others: (leave.data ?? []).filter((x) => x.user_id !== me).length, again: again.error?.code }
  })
  if (r.changed) throw new Error('staff changed settings')
  if (r.insights !== '42501') throw new Error('insights open to staff: ' + r.insights)
  if (r.others) throw new Error(`read ${r.others} colleagues' leave rows`)
  if (r.again !== '23505') throw new Error('double sign-in: ' + r.again)
  if (await page.getByRole('navigation', { name: 'Main' }).first().getByRole('link', { name: 'Insights' }).count()) throw new Error('Insights in nav')
})
